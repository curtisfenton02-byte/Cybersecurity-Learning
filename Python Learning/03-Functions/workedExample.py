def multiply(x, y):#python stores a function called multiply
    result = x * y#now we have 4 * 5
    return result#return stores 20 and sends it back to answer

answer = multiply(4, 5)
#function is called and values 4, 5 are passed into the parameter

#function call gets replaced with the returned value (20) so
#the above line is now answer = 20

print(answer)#this becomes print(20)
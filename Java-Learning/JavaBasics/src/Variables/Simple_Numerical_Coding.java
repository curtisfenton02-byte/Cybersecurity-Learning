package Variables;

public class Simple_Numerical_Coding {
    public static void main(String[] args) {
        int integer1;
        int integer2;
        int sum;
        int sub;
        int multi;
        int div;
        int rem;

        integer1 = 10;
        integer2 = 20;
        sum = integer1 + integer2;
        sub = integer1 - integer2;
        multi = integer1 * integer2;
        div = integer1 / integer2;
        rem = integer1 % integer2;

        System.out.println("The sum value is: " + sum);
        System.out.println("The subtraction value is: " + sub);
        System.out.println("The multiplaction value is: " + multi);
        System.out.println("The division value is: " + div);
        System.out.println("The remainder value is: " + rem);
    }
}
